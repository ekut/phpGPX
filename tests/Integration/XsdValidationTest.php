	/**
	 * Test that GPX files with boundary coordinate values validate against the XSD.
	 *
	 * Requirements: 1.4, 1.5, 2.4, 2.5
	 */
	public function test_gpx_file_with_boundary_coordinates_validates_against_xsd(): void
	{
		// Arrange - Create GPX file with boundary coordinate values
		$gpxFile = new GpxFile('phpGPX Boundary Test');

		// Add waypoints at coordinate boundaries
		$waypoints = [
			// Latitude boundaries
			PointFactory::create(['pointType' => Point::WAYPOINT, 'latitude' => -90.0, 'longitude' => 0.0]),
			PointFactory::create(['pointType' => Point::WAYPOINT, 'latitude' => 90.0, 'longitude' => 0.0]),
			// Longitude boundaries
			PointFactory::create(['pointType' => Point::WAYPOINT, 'latitude' => 0.0, 'longitude' => -180.0]),
			PointFactory::create(['pointType' => Point::WAYPOINT, 'latitude' => 0.0, 'longitude' => 179.999999]),
		];

		foreach ($waypoints as $waypoint) {
			$gpxFile->waypoints[] = $waypoint;
		}

		// Add bounds at boundaries
		$metadata = MetadataFactory::create(['name' => 'Boundary Test']);
		$metadata->bounds = new Bounds(
			minLatitude: -90.0,
			minLongitude: -180.0,
			maxLatitude: 90.0,
			maxLongitude: 179.999999,
		);
		$gpxFile->metadata = $metadata;

		// Act - Generate XML
		$xml = $gpxFile->toXML()->saveXML();

		// Assert - Validate against XSD
		$result = XsdValidator::validate($xml);

		$this->assertTrue(
			$result['valid'],
			'GPX file with boundary coordinates should validate against XSD. Errors: ' . implode('; ', $result['errors']),
		);
	}

