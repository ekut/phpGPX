	 *
	 * Requirements: 12.1, 12.2, 12.3
	 */
	public function test_minimal_gpx_file_validates_against_xsd(): void
	{
		// Arrange - Create minimal GPX file with only required elements
		$gpxFile = new GpxFile('phpGPX XSD Test');

		// Act - Generate XML
		$xml = $gpxFile->toXML()->saveXML();

		// Assert - Validate against XSD
		$result = XsdValidator::validate($xml);

		$this->assertTrue(
			$result['valid'],
			'Minimal GPX file should validate against XSD. Errors: ' . implode('; ', $result['errors']),
		);
	}

