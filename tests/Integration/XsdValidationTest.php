	/**
	 * Test that a comprehensive GPX file with all elements validates against the XSD.
	 *
	 * Requirements: All
	 */
	public function test_comprehensive_gpx_file_validates_against_xsd(): void
	{
		// Arrange - Create comprehensive GPX file with all element types
		$gpxFile = new GpxFile('phpGPX Comprehensive Test');

		// Add comprehensive metadata
		$metadata = MetadataFactory::create([
			'name' => 'Comprehensive Test GPX',
			'description' => 'A GPX file with all possible elements',
			'time' => new DateTime('2024-01-15T10:30:00Z'),
			'keywords' => 'comprehensive, test, validation',
		]);

		// Add bounds
		$metadata->bounds = new Bounds(
			minLatitude: 54.0,
			minLongitude: 9.0,
			maxLatitude: 55.0,
			maxLongitude: 10.0,
		);

		// Add link
		$metadata->links[] = new Link('https://example.com/comprehensive-test');

		// Add copyright
		$metadata->copyright = new Copyright('Comprehensive Test Author');
		$metadata->copyright->year = '2024';

		// Add author with email
		$metadata->author = new \phpGPX\Models\Person();
		$metadata->author->name = 'Test Author';
		$metadata->author->email = new Email('author', 'example.com');

		$gpxFile->metadata = $metadata;

		// Add waypoints
		$waypoint = PointFactory::create([
			'pointType' => Point::WAYPOINT,
			'latitude' => 54.9328621088893,
			'longitude' => 9.860624216140083,
			'elevation' => 42.5,
			'name' => 'Comprehensive Waypoint',
			'description' => 'A waypoint with all properties',
		]);
		$gpxFile->waypoints[] = $waypoint;

		// Add track
		$track = TrackFactory::createWithSegments(2, 3);
		$track->name = 'Comprehensive Track';
		$track->description = 'A track with multiple segments';
		$gpxFile->tracks[] = $track;

		// Add route
		$route = new Route();
		$route->name = 'Comprehensive Route';
		$route->description = 'A route with multiple points';
		$route->points[] = PointFactory::create(['pointType' => Point::ROUTEPOINT]);
		$route->points[] = PointFactory::create(['pointType' => Point::ROUTEPOINT]);
		$gpxFile->routes[] = $route;

		// Act - Generate XML
		$xml = $gpxFile->toXML()->saveXML();

		// Assert - Validate against XSD
		$result = XsdValidator::validate($xml);

		$this->assertTrue(
			$result['valid'],
			'Comprehensive GPX file should validate against XSD. Errors: ' . implode('; ', $result['errors']),
		);
	}

